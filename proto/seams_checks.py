q = 3


def poly(cs):
    return nmod_poly([c % q for c in cs], q)


Tpol = None
ZERO = None
ONEp = None


def monic(p):
    lc = int(p.leading_coefficient())
    return p * pow(lc, -1, q), lc


class RF:
    """Rational function num/den over F_3, den monic, gcd 1."""

    def __init__(self, num, den=None):
        if den is None:
            den = ONEp
        if den.is_zero():
            raise ZeroDivisionError
        g = num.gcd(den) if not num.is_zero() else den
        num = num // g
        den = den // g
        den, lc = monic(den)
        num = num * pow(lc, -1, q)
        self.num, self.den = num, den

    def __add__(s, o):
        return RF(s.num * o.den + o.num * s.den, s.den * o.den)

    def __sub__(s, o):
        return RF(s.num * o.den - o.num * s.den, s.den * o.den)

    def __mul__(s, o):
        return RF(s.num * o.num, s.den * o.den)

    def __truediv__(s, o):
        return RF(s.num * o.den, s.den * o.num)

    def __eq__(s, o):
        return s.num == o.num and s.den == o.den

    def iszero(s):
        return s.num.is_zero()

    def is_poly(s):
        return s.den.is_one()

    def lc(s):
        """Leading coefficient at infinity (the 'sign': the unit part of the expansion in s)."""
        return int(s.num.leading_coefficient()) * pow(int(s.den.leading_coefficient()), -1, q) % q

    def v_inf(s):
        return s.den.degree() - s.num.degree()


def rfgcd(xs):
    """Monic generator of the F_3[T]-module generated by rational functions (0 if all are 0)."""
    xs = [x for x in xs if not x.iszero()]
    if not xs:
        return RF(ZERO)
    D = ONEp
    for x in xs:
        D = D * x.den // D.gcd(x.den)
    g = ZERO
    for x in xs:
        g = g.gcd(x.num * (D // x.den)) if not g.is_zero() else monic(x.num * (D // x.den))[0]
    return RF(g, D)


def divides(G, x):
    """x lies in G F_3[T] (G a rational function, not 0)."""
    return (x / G).is_poly()


def laurent_inf(f, n):
    """Coefficients {k: c_k} of f = sum c_k s^k, s = 1/T, for v_inf(f) <= k < n."""
    if f.iszero():
        return {}
    v = f.v_inf()
    if n <= v:
        return {}
    nr = f.num.reverse()  # num(T) = T^deg num * nr(s)
    dr = f.den.reverse()
    L = n - v
    ser = (nr * dr.inverse_series_trunc(L)).truncate(L)
    cs = ser.coeffs()
    return {v + i: int(cs[i]) for i in range(len(cs)) if int(cs[i]) != 0}


def res_inf(f):
    """Res_inf(f dT) = - c_1, since dT = - s^-2 ds (seams.md, F.6)."""
    return (-laurent_inf(f, 2).get(1, 0)) % q


def res_linear(f, c):
    """Res at T = c of f dT: coefficient of u^-1 in the expansion in u = T - c."""
    sh = poly([c, 1])
    num = f.num.compose(sh)
    den = f.den.compose(sh)
    m = 0
    cs = den.coeffs()
    while int(cs[m]) == 0:
        m += 1
    if m == 0:
        return 0
    h1 = den.right_shift(m) if hasattr(den, "right_shift") else den // poly([0] * m + [1])
    ser = (num * h1.inverse_series_trunc(m)).truncate(m)
    cs = ser.coeffs()
    return int(cs[m - 1]) % q if len(cs) >= m else 0


def trace_mod(e, Pp):
    """Trace from F_3[T]/(P) to F_3 of the class of e."""
    d = Pp.degree()
    t = 0
    for i in range(d):
        prod = (e * poly([0] * i + [1])) % Pp
        cs = prod.coeffs()
        t += int(cs[i]) if len(cs) > i else 0
    return t % q


def res_simple(f, Pp):
    """Res at an irreducible P of f dT when f has at most a simple pole at P: Tr((num / (h P'))(theta))."""
    den = f.den
    if not (den % Pp).is_zero():
        return 0
    h = den // Pp
    assert not (h % Pp).is_zero(), "res_simple needs a simple pole"
    e =(h * Pp.derivative()) % Pp
    g, sI, _ = e.xgcd(Pp)
    inv = sI * pow(int(g.leading_coefficient()), -1, q)
    return trace_mod((f.num * inv) % Pp, Pp)


