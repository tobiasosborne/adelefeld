    report("F2 affine product rule ab + gcd(aM, bN, NM) (monic gcd): enclosure and tight", bad == 0,
           f"300 random cases, {bad} failures")
    report("F2 mutant (without NM) is detected", mut > 0, f"{mut} of 300 cases fail")
    # F.3 product rule at infinity: radius exponent min(v(a)+m, v(b)+n, n+m)
    S = 12  # common shift: an element is p(s) / s^S with p a polynomial in s

    def ser(v, cs):
        return poly([0] * (v + S) + cs)

    def val(p, shift):
        if p.is_zero():
            return None
        cs = p.coeffs()
        k = 0
        while int(cs[k]) == 0:
            k += 1
        return k - shift

