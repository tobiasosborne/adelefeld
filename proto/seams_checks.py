    # F.2 affine product rule with monic gcd
    def rpoly(dmax):
        return poly([rng.randint(0, 2) for _ in range(rng.randint(0, dmax + 1))])

    def rrf(dn=3, dd=2, zero_ok=True):
        n = rpoly(dn)
        if not zero_ok and n.is_zero():
            n = ONEp
        dden = rpoly(dd)
        if dden.is_zero():
            dden = ONEp
        return RF(n, dden)

    def rmonic(dmax):
        """A random monic polynomial of degree 0..dmax."""
        return monic(poly([rng.randint(0, 2) for _ in range(rng.randint(0, dmax))] + [rng.randint(1, 2)]))[0]

