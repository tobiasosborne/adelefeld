/* tests/test_modctx.c: the modulus contexts of include/adelefeld/modctx.h.

   Ground truth: tests/ref/vectors/m1-modctx/modctx.jsonl, generated by
   lanes/m1-modctx-b/gen_modctx_vectors.py from tests/ref/adfref/modctx_ref.py (CONVENTIONS
   legal: the vectors are the oracle, the C test does not import the reference).  The golden
   file tests/golden/dump.tsv carries the modctx bodies of the dump form with their statuses.
   The constructors, the coefficients and the statuses are those of docs/conventions.md 5.14,
   3.2 and 10.2; the reduction and the recombination are policies.md Lemma 17.

   The internal kernels adf_modctx_reduce / adf_modctx_recombine are declared here by hand;
   they are hidden symbols of the library (src/modctx.c), not part of the public interface.

   The tests also cover: every validation failure with *out untouched; the round trip integer
   to residues to integer for 1, 2, 64 and 128 blocks; the descriptor functions; two threads
   reading one context at the same time. */

