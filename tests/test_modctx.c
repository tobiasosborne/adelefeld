/* ------------------------------------------------------------------ dump edge cases */

/* Call new_from_dump on a text of `len` bytes and return the status. */
static int
from_dump_status(const char * text, size_t len)
{
    adf_modctx_struct * ctx = NULL;
    int st = adf_modctx_new_from_dump(&ctx, text, len, 0, NULL);
    adf_modctx_free(ctx);
    return st;
}

/* The byte length of a literal, embedded NUL included. */
#define FDS(lit) from_dump_status((lit), sizeof(lit) - 1)

ADF_TEST(from_dump_edge_cases)
{
    adf_text_limits_t lim;
    adf_modctx_struct * ctx = NULL;

    /* a forbidden byte: NUL and 0x01 (stage 2, before the grammar) */
    ADF_CHECK(FDS("adf1 Q modctx 6 1 6\x00") == ADF_PARSE);
    ADF_CHECK(FDS("adf1 Q modctx 6 1 6\x01") == ADF_PARSE);
    ADF_CHECK(FDS("adf\x00") == ADF_PARSE);

    /* the version: adf0 is UNSUPPORTED, adf01 is PARSE */
    ADF_CHECK(FDS("adf0 Q modctx 6 1 6") == ADF_UNSUPPORTED);
    ADF_CHECK(FDS("adf01 Q modctx 6 1 6") == ADF_PARSE);
    ADF_CHECK(FDS("adf2 Q modctx 6 1 6") == ADF_UNSUPPORTED);

    /* hex tokens: a leading 'a' and a later 'a' are accepted, 'g' and '-0' are not */
    ADF_CHECK(FDS("adf1 Q modctx a 0") == ADF_OK);
    ADF_CHECK(FDS("adf1 Q modctx 1a 0") == ADF_OK);
    ADF_CHECK(FDS("adf1 Q modctx g 0") == ADF_PARSE);
    ADF_CHECK(FDS("adf1 Q modctx -0 0") == ADF_PARSE);
    ADF_CHECK(FDS("adf1 Q modctx 07 1 7") == ADF_PARSE);
    ADF_CHECK(FDS("adf1 Q modctx 6 1 -6") == ADF_DOMAIN);

    /* a non-coprime pair whose product still equals K is DOMAIN */
    ADF_CHECK(FDS("adf1 Q modctx 8 2 2 4") == ADF_DOMAIN);

    /* a count that does not fit a size_t is a grammar failure, not a limit */
    ADF_CHECK(FDS("adf1 Q modctx 6 fffffffffffffffff 6") == ADF_PARSE);

    /* limits: max_items = 0 permits k = 0 and forbids k = 1 */
    adf_text_limits_default(&lim);
    lim.max_items = 0;
    ADF_CHECK(adf_modctx_new_from_dump(&ctx, "adf1 Q modctx 6 0", 17, 0, &lim) == ADF_OK);
    adf_modctx_free(ctx);
    ctx = NULL;
    ADF_CHECK(adf_modctx_new_from_dump(&ctx, "adf1 Q modctx 6 1 6", 19, 0, &lim) == ADF_LIMIT);
    ADF_CHECK(ctx == NULL);
}

/* The same body, but a context with many blocks: a heap under-allocation in the loader
   corrupts memory and a wrong block count is caught by the round trip. */
ADF_TEST(from_dump_many_blocks)
{
    ulong q[2000];
    adf_modctx_struct * ctx = NULL;
    adf_modctx_struct * copy = NULL;
    char * text;
    size_t len, dlen;
    ulong p = 2;
    int i;

    for (i = 0; i < 2000; i++)
    {
        q[i] = p;
        p = n_nextprime(p, 0);
    }
    ADF_CHECK(adf_modctx_new_blocks(&ctx, q, 2000) == ADF_OK);
    text = adf_modctx_dump_str(&len, ctx);
    ADF_CHECK(adf_modctx_new_from_dump(&copy, text, len, 0, NULL) == ADF_OK);
    ADF_CHECK(adf_modctx_nblocks(copy) == 2000);
    for (i = 0; i < 2000; i++)
        ADF_CHECK(adf_modctx_block(copy, i) == q[i]);
    {
        char * again = adf_modctx_dump_str(&dlen, copy);
        ADF_CHECK(dlen == len && memcmp(again, text, len) == 0);
        flint_free(again);
    }
    adf_modctx_free(copy);
    adf_modctx_free(ctx);
    flint_free(text);
}

/* A text with no terminating NUL at the end of a mapped page: the last byte is the last
   byte of the mapping and the next page is inaccessible.  A parser that reads s[len] for a
   lookahead faults; new_from_dump must not.  This is the check of conventions 8.1. */
ADF_TEST(dump_input_without_terminator)
{
    long pg = sysconf(_SC_PAGESIZE);
    const char * cases[] = {"adf1", "adf1 Q ", "adf1 Q", "adf1 Q modctx",
                            "adf1 Q modctx 6 2 2", "adf1 Q modctx 6",
                            "adf1 Q modctx -"};
    size_t n = sizeof(cases) / sizeof(cases[0]);
    size_t i;

    ADF_CHECK(pg > 0);
    if (pg <= 0)
        return;
    for (i = 0; i < n; i++)
    {
        size_t len = strlen(cases[i]);
        char * base = mmap(NULL, (size_t) pg * 2, PROT_READ | PROT_WRITE,
                           MAP_PRIVATE | MAP_ANONYMOUS, -1, 0);
        char * p;
        int st;

        ADF_CHECK(base != MAP_FAILED);
        if (base == MAP_FAILED)
            continue;
        ADF_CHECK(mprotect(base + pg, (size_t) pg, PROT_NONE) == 0);
        p = base + pg - len;
        memcpy(p, cases[i], len);
        st = from_dump_status(p, len);
        ADF_CHECK_MSG(st == ADF_PARSE, "case \"%s\": status %s", cases[i],
                      adf_status_str(st));
        munmap(base, (size_t) pg * 2);
    }
}

