/* tests/test_scaled_vectors.c: the scaled-residue policy against the JSON-lines vector oracles.

   Two files are run completely (lanes/COMMON-C.md rule 2):

   - tests/ref/vectors/policies.jsonl, the scaled rows: "convert_from_tight" (360 rows),
     "scaled_add" (300) and "scaled_mul" (300).  This is the general oracle, written from
     tests/ref/adfref/policies.py (convert_from_tight: Proposition 6(1) of
     docs/proofs/precision.md line 106 and policies Proposition 7 line 139; scaled_add:
     precision Proposition 5(1) line 99 with the exact-operand fallback of policies
     Proposition 8 line 159; scaled_mul: precision Proposition 5(2) and policies Proposition 9
     line 184).  The "absolute_cap" rows belong to tests/test_cap_vectors.c and are skipped here.

   - tests/ref/vectors/m1-scaled/scaled_ops.jsonl (1762 rows), the rows the general oracle does
     not have: neg, sub, scale, add_rat, mul with mixed exact operands, mul_tight
     (policies Proposition 10.3 line 200), set_context (policies Proposition 11 line 218) and
     to_fball.  Generated by lanes/m1-scaled/gen_scaled_vectors.py from the same Python
     reference plus the two formulas above, each cross-checked in the generator.

   Every scaled operand of a binary row is built in one context per modulus K, so the operands of
   a binary row share one context pointer (the shared-pointer rule of conventions 4.6 and SPEC
   4.4); a row whose operands would not share a pointer is not a row of these files.  Values are
   built only through the public API: a scaled value {s, u, K} is the ball s u + s K Zhat put
   through adf_scaled_set_fball, which stores exactly (s, u) by policies Lemma 5 (line 113). */

