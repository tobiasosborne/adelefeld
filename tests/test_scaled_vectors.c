/* Rows of the shape {op, a, [q], result}: neg, scale, sub, mul_exact, mul_tight. */
static void
run_lane_row(const char * path, const char * want_op, int kind, size_t want_rows)
{
    /* kind: 0 = unary neg, 1 = scale (a, q), 2 = binary (a, b) */
    jsonl_error_t err;
    jsonl_file * f = NULL;
    ctx_cache cache;
    size_t i, n = 0;

    cache_init(&cache);
    ADF_CHECK_MSG(jsonl_open(path, &f, &err) == 1, "%s", jsonl_error_message(&err));
    if (f == NULL)
        return;
    for (i = 0; i < jsonl_count(f); i++)
    {
        const jsonl_value * rec = jsonl_record(f, i);
        const jsonl_value * opv, * ja, * jb, * jq, * jres;
        const char * op;
        size_t oplen;
        const adf_modctx_struct * ctx;
        adf_scaled_t x, y, z;
        adf_rat_t q;

        ADF_CHECK(jsonl_field(rec, "op", &opv, &err) == 1);
        op = jsonl_string(opv, &oplen, &err);
        ADF_CHECK(op != NULL);
        if (op == NULL || strcmp(op, want_op) != 0)
            continue;
        n++;

        ADF_CHECK(jsonl_field(rec, "a", &ja, &err) == 1);
        ADF_CHECK(jsonl_field(rec, "result", &jres, &err) == 1);
        if (kind == 2)
        {
            ADF_CHECK(jsonl_field(rec, "b", &jb, &err) == 1);
            ctx = binary_ctx(&cache, ja, jb, &err);
        }
        else
            ctx = cache_get(&cache, value_Ktext(ja, &err) != NULL ? value_Ktext(ja, &err) : "1");
        ADF_CHECK(ctx != NULL);
        adf_scaled_init(x, ctx);
        adf_scaled_init(y, ctx);
        adf_scaled_init(z, ctx);
        adf_rat_init(q);
        ADF_CHECK(build_value(x, ja, ctx, &err));
        if (kind == 0)
        {
            adf_scaled_neg(y, x);
            ADF_CHECK(value_equals_json(y, jres, &err));
        }
        else if (kind == 1)
        {
            ADF_CHECK(jsonl_field(rec, "q", &jq, &err) == 1);
            ADF_CHECK(json_rat(q, jq, &err));
            adf_scaled_mul_rat(y, x, q);
            ADF_CHECK(adf_scaled_context(y) == ctx);
            ADF_CHECK(value_equals_json(y, jres, &err));
        }
        else
        {
            ADF_CHECK(build_value(y, jb, ctx, &err));
            if (strcmp(want_op, "sub") == 0)
                ADF_CHECK(adf_scaled_sub(z, x, y) == ADF_OK);
            else if (strcmp(want_op, "mul_exact") == 0)
                ADF_CHECK(adf_scaled_mul(z, x, y) == ADF_OK);
            else
                ADF_CHECK(adf_scaled_mul_tight(z, x, y) == ADF_OK);
            ADF_CHECK(adf_scaled_context(z) == ctx);
            ADF_CHECK(value_equals_json(z, jres, &err));
        }
        ADF_CHECK(adf_scaled_is_canonical(kind == 0 || kind == 1 ? y : z));
        adf_scaled_clear(x);
        adf_scaled_clear(y);
        adf_scaled_clear(z);
        adf_rat_clear(q);
    }
    jsonl_close(f);
    cache_clear(&cache);
    ADF_CHECK_MSG(n == want_rows, "expected %lu %s rows in %s, found %lu",
                  (unsigned long) want_rows, want_op, path, (unsigned long) n);
}

